@st.cache_data(ttl=300) # Update setiap 5 menit
def fetch_news():
    # Daftar RSS Feed Prioritas (Dapat diperluas sesuai list)
    rss_feeds = {
        "CNBC Market": "https://www.cnbcindonesia.com/market/rss",
        "Kontan Investasi": "https://rss.kontan.co.id/news/investasi",
        "Bisnis Market": "https://www.bisnis.com/rss/market",
        "Antara Ekonomi": "https://www.antaranews.com/rss/ekonomi.xml",
        "Sindonews Ekbis": "https://ekbis.sindonews.com/rss",
        "Detik Finance": "https://rss.detik.com/index.php/finance",
        "IDX Channel": "https://www.idxchannel.com/rss",
        "Google News (IDX)": "https://news.google.com/rss/search?q=saham+BEI+OR+IHSG+when:1d&hl=id&gl=ID&ceid=ID:id"
    }

    news_data = []

    def parse_feed(source, url):
        try:
            feed = feedparser.parse(url)
            for entry in feed.entries[:10]: # Ambil 10 berita terbaru per sumber
                news_data.append({
                    "Waktu": entry.published if hasattr(entry, 'published') else datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                    "Sumber": source,
                    "Judul Berita": entry.title,
                    "Link": entry.link
                })
        except Exception:
            pass

    # Fetch paralel untuk efisiensi
    with concurrent.futures.ThreadPoolExecutor() as executor:
        futures = [executor.submit(parse_feed, source, url) for source, url in rss_feeds.items()]
        concurrent.futures.wait(futures)

    df_news = pd.DataFrame(news_data)
    if not df_news.empty:
        # Konversi waktu agar bisa di-sort (simplifikasi)
        df_news['Waktu'] = pd.to_datetime(df_news['Waktu'], errors='coerce')
        df_news = df_news.sort_values(by='Waktu', ascending=False).head(50)
    return df_news

