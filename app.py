# 2. MODUL TECHNICAL ANALYSIS & SCREENER
# ==========================================
def calculate_indicators(df):
    """Menghitung MA, MACD, RSI, VWAP, Squeeze, dan Gap"""
    if len(df) < 30:
        return df

    # Moving Averages
    df['MA20'] = df['Close'].rolling(window=20).mean()
    df['MA50'] = df['Close'].rolling(window=50).mean()

    # VWAP (Volume Weighted Average Price) untuk Intraday
    df['Typical_Price'] = (df['High'] + df['Low'] + df['Close']) / 3
    df['VWAP'] = (df['Typical_Price'] * df['Volume']).cumsum() / df['Volume'].cumsum()

    # MACD
    exp1 = df['Close'].ewm(span=12, adjust=False).mean()
    exp2 = df['Close'].ewm(span=26, adjust=False).mean()
    df['MACD'] = exp1 - exp2
    df['Signal_Line'] = df['MACD'].ewm(span=9, adjust=False).mean()

    # RSI (14)
    delta = df['Close'].diff()
    up = delta.clip(lower=0)
    down = -1 * delta.clip(upper=0)
    ema_up = up.ewm(com=13, adjust=False).mean()
    ema_down = down.ewm(com=13, adjust=False).mean()
    rs = ema_up / ema_down
    df['RSI'] = 100 - (100 / (1 + rs))

    # TTM Squeeze Strategy
    # Bollinger Bands
    df['BB_std'] = df['Close'].rolling(window=20).std()
    df['BB_upper'] = df['MA20'] + (df['BB_std'] * 2)
    df['BB_lower'] = df['MA20'] - (df['BB_std'] * 2)

    # Keltner Channels
    df['TR'] = np.maximum((df['High'] - df['Low']),
                          np.maximum(abs(df['High'] - df['Close'].shift()),
                                     abs(df['Low'] - df['Close'].shift())))
    df['ATR'] = df['TR'].rolling(window=20).mean()
    df['KC_upper'] = df['MA20'] + (df['ATR'] * 1.5)
    df['KC_lower'] = df['MA20'] - (df['ATR'] * 1.5)

    # Squeeze Firing: True jika BB masuk ke dalam KC lalu mulai keluar
    df['Squeeze_On'] = (df['BB_lower'] > df['KC_lower']) & (df['BB_upper'] < df['KC_upper'])

    return df

@st.cache_data(ttl=900) # Update setiap 15 menit
def scan_stocks():
    # Load daftar saham
    try:
        emiten_df = pd.read_csv("daftar_lengkap_saham_indonesia_bei.csv")
        # Menggunakan kolom Ticker_Yahoo_Finance
        tickers = emiten_df['Ticker_Yahoo_Finance'].dropna().unique().tolist()
    except Exception as e:
        st.error(f"Gagal memuat file daftar saham: {e}")
        return pd.DataFrame()

    # Untuk kecepatan di dashboard live, kita bisa sampling / menggunakan subset saham paling liquid.
    # Disini dibatasi ke 50 saham pertama untuk demo performa, hilangkan limit [:50] untuk scan keseluruhan.
    tickers_to_scan = tickers[:50]

    results = []

    def process_ticker(ticker):
        try:
            # Ambil data intraday 15 menit, untuk 5 hari terakhir
            data = yf.download(ticker, period="5d", interval="15m", progress=False)
            if len(data) == 0:
                return None

            df = calculate_indicators(data)
            latest = df.iloc[-1]
            prev = df.iloc[-2]

            # Strategi: The Opening Gap
            # Gap up dari close kemarin ke open sesi ini
            is_gap_up = latest['Open'] > prev['Close'] * 1.01

            # Strategi: TTM Squeeze firing (Momentum expansion)
            squeeze_firing = not latest['Squeeze_On'] and prev['Squeeze_On']

            # Momentum MACD & Volume Spike
            macd_bullish = latest['MACD'] > latest['Signal_Line']
            volume_spike = latest['Volume'] > df['Volume'].rolling(20).mean().iloc[-1] * 2

            # VWAP support
            above_vwap = latest['Close'] > latest['VWAP']

            # Menentukan Sinyal Scalping
            signal = "HOLD / SKIP"
            if is_gap_up and volume_spike and above_vwap:
                signal = "🔥 STRONG BUY (Gap Play)"
            elif squeeze_firing and macd_bullish and above_vwap:
                signal = "🚀 BUY (Squeeze Momentum)"
            elif latest['RSI'] > 75 or latest['Close'] < latest['VWAP']:
                signal = "⚠️ SELL (Take Profit / Cut)"

            if signal != "HOLD / SKIP":
                return {
                    "Ticker": ticker.replace(".JK", ""),
                    "Harga Terakhir": round(latest['Close'], 0),
                    "RSI": round(latest['RSI'], 2),
                    "MACD": round(latest['MACD'], 2),
                    "Sinyal": signal
                }
        except Exception:
            return None

    with concurrent.futures.ThreadPoolExecutor(max_workers=10) as executor:
        futures = [executor.submit(process_ticker, t) for t in tickers_to_scan]
        for f in concurrent.futures.as_completed(futures):
            res = f.result()
            if res:
                results.append(res)

    return pd.DataFrame(results)

